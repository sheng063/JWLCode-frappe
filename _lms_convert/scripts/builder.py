#!/usr/bin/env python3
"""Build and validate one legacy-icpc problem package.

Usage:
  python builder.py <problem_dir> [--compile-only]

A "complete" problem directory looks like:
  <pid>/
    problem.yaml
    problem_statement/problem.zh.tex
    data/sample/<NN>.in|.ans
    data/secret/<NN>.in|.ans          (some may be present, some generated)
    submissions/accepted/solution.cpp
    input_validators/validator.py

This script will:
  1. compile solution.cpp
  2. cross-check the solution against problem_info.json lms_test_cases
  3. for every sample+secret .in, run the solution; if an .ans is missing it
     is generated by running the solution; an existing .ans must match
  4. run input_validators/validator.py on every sample+secret .in (exit 42)
  5. zip to <out>/<pid>.zip  with a single <pid>/ root, no junk files
"""
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import zipfile

SCRIPTS = os.path.dirname(os.path.abspath(__file__))
WORK = os.path.join(SCRIPTS, "..")
OUT = os.path.join(WORK, "out")
BASEDIR = os.path.join(WORK, "problems")

CXX = os.environ.get("CXX", "g++")
PY = os.environ.get("PY", sys.executable)


def sh(*args, **kw):
    return subprocess.run(args, capture_output=True, text=True, **kw)


def list_pairs(d):
    """Return [(num, inPath, ansPath)] sorted by numeric basename."""
    pairs = []
    if not os.path.isdir(d):
        return pairs
    ins = [f for f in os.listdir(d) if f.endswith(".in")]
    for f in sorted(ins, key=lambda x: int(re.search(r"(\d+)", x).group(1)) if re.search(r"(\d+)", x) else 0):
        base = f[:-3]
        pairs.append((base, os.path.join(d, f), os.path.join(d, base + ".ans")))
    return pairs


def renumber(d):
    """Re-number sample/secret .in/.ans files to zero-padded contiguous."""
    pairs = list_pairs(d)
    width = 3 if len(pairs) >= 100 else 2
    for i, (base, inpath, anspath) in enumerate(pairs, 1):
        newbase = str(i).zfill(width)
        if base == newbase:
            continue
        newin = os.path.join(d, newbase + ".in")
        newans = os.path.join(d, newbase + ".ans")
        os.replace(inpath, newin)
        if os.path.exists(anspath):
            os.replace(anspath, newans)
    return len(pairs)


def compile_solution(prob_dir):
    src = os.path.join(prob_dir, "submissions", "accepted", "solution.cpp")
    if not os.path.exists(src):
        return None, "solution.cpp missing"
    exe = os.path.join(prob_dir, "solution.exe")
    r = sh(CXX, "-std=c++17", "-O2", "-o", exe, src)
    if r.returncode != 0:
        return None, r.stderr[-2000:]
    return exe, None


def run(exe, inp):
    r = sh(exe, input=inp)
    return r.returncode, r.stdout, r.stderr


def norm(out):
    return out.rstrip("\r\n")


def cross_check(prob_dir, exe, info):
    """Run solution on every LMS test case; report mismatches."""
    mism = []
    lms = info.get("lms_test_cases", []) or []
    for t in lms:
        rc, out, _ = run(exe, (t["input"] or "") + ("\n" if t["input"] else ""))
        if rc != 0 or norm(out) != norm(t["output"]):
            mism.append({"idx": t.get("idx"), "input": t.get("input"),
                         "expected": norm(t["output"]), "actual": norm(out), "rc": rc})
    return mism


def process_cases(prob_dir, exe):
    """Run solution on all sample+secret .in; generate missing .ans; report."""
    report = {"sample": [], "secret": [], "generated": 0, "mismatch": []}
    for sub in ("sample", "secret"):
        pairs = list_pairs(os.path.join(prob_dir, "data", sub))
        for base, inp, ans in pairs:
            with open(inp, "r", encoding="utf-8") as f:
                data = f.read()
            rc, out, _ = run(exe, data)
            got = norm(out)
            if os.path.exists(ans):
                with open(ans, "r", encoding="utf-8") as f:
                    exp = norm(f.read())
                ok = (rc == 0 and got == exp)
                if not ok:
                    report["mismatch"].append({"dir": sub, "base": base, "expected": exp, "actual": got, "rc": rc})
            else:
                # generate .ans from the solution run
                with open(ans, "w", encoding="utf-8", newline="\n") as f:
                    f.write(got + ("\n" if got else ""))
                report["generated"] += 1
                ok = True
            report[sub].append({"base": base, "ok": ok, "got": got})
    return report


def validate_inputs(prob_dir, py):
    """Run input validator on every sample+secret .in; must exit 42."""
    results = []
    for sub in ("sample", "secret"):
        pairs = list_pairs(os.path.join(prob_dir, "data", sub))
        for base, inp, _ in pairs:
            r = sh(py, os.path.join(prob_dir, "input_validators", "validator.py"), stdin=open(inp))
            results.append({"dir": sub, "base": base, "exit": r.returncode})
    return results


def zip_problem(prob_dir, pid):
    os.makedirs(OUT, exist_ok=True)
    zpath = os.path.join(OUT, pid + ".zip")
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for root, dirs, files in os.walk(prob_dir):
            # skip build artifacts
            dirs[:] = [d for d in dirs if d not in ("solution.exe", "__pycache__", "out")]
            for f in files:
                if f == "solution.exe" or f.endswith(".pyc"):
                    continue
                if f == "problem_info.json":
                    continue
                full = os.path.join(root, f)
                rel = os.path.relpath(full, prob_dir)
                arcname = pid + "/" + rel
                z.write(full, arcname)
    return zpath


def main():
    if len(sys.argv) < 2:
        print("usage: builder.py <problem_dir>")
        return 2
    prob_dir = os.path.abspath(sys.argv[1])
    pid = os.path.basename(prob_dir)
    info_path = os.path.join(prob_dir, "problem_info.json")
    info = {}
    if os.path.exists(info_path):
        with open(info_path, encoding="utf-8") as f:
            info = json.load(f)

    exe, err = compile_solution(prob_dir)
    if err:
        print("FAIL compile: " + err)
        return 1
    print("compiled", exe)

    # Normalize zero-padded numbering for sample+secret before processing.
    for sub in ("sample", "secret"):
        renumber(os.path.join(prob_dir, "data", sub))

    mism = cross_check(prob_dir, exe, info)
    print("cross_check lms mismatches:", len(mism))
    for m in mism[:10]:
        print("  LMS MISMATCH:", m)

    rep = process_cases(prob_dir, exe)
    print("cases: sample=%d secret=%d generated_ans=%d mismatches=%d" % (
        len(rep["sample"]), len(rep["secret"]), rep["generated"], len(rep["mismatch"])))
    for m in rep["mismatch"][:20]:
        print("  CASE MISMATCH:", m)

    val = validate_inputs(prob_dir, PY)
    bad = [v for v in val if v["exit"] != 42]
    print("validator: total=%d non42=%d" % (len(val), len(bad)))
    for v in bad[:20]:
        print("  VALIDATOR NON-42:", v)

    ok = not mism and not rep["mismatch"] and not bad
    zpath = zip_problem(prob_dir, pid)
    print("zip ->", zpath, "OK" if ok else "HAS-ISSUES")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
