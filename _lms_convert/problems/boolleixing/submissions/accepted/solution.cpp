#include <iostream>

int main() {
    // This problem has no input.
    // A bool variable assigned the logical value false evaluates to 0.
    bool b = false;
    std::cout << b << "\n";
    // Applying the logical NOT operator ! to that variable flips it: !false == true == 1.
    std::cout << !b << "\n";
    return 0;
}
